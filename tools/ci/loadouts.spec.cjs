    G.player.weapons[0].level=5;
    const save=L.save('Veteran'),duplicate=L.save('veteran');
    const two=L.save('Second'),three=L.save('Third'),full=L.save('Fourth');
    const rename=L.rename('Second','Renamed');
    const ship=L.find('Veteran');
